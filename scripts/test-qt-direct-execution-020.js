'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const Module = require('module');

const originalLoad = Module._load;
Module._load = function patchedLoad(request, parent, isMain) {
  if (request === 'vscode') {
    return {
      workspace: {
        getConfiguration: () => ({ get: (_key, fallback) => fallback, update: async () => undefined })
      },
      ConfigurationTarget: { Global: 1, Workspace: 2 }
    };
  }
  return originalLoad.call(this, request, parent, isMain);
};

const model = require('../out/model/qtProjectManifest');
const qtInstallations = require('../out/services/qpmQtInstallationService');
const direct = require('../out/services/qpmQtDirectBuildService');

function write(filePath, content = '') {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
}

function makeFakeTool(filePath) {
  const script = [
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    'if [[ "${1:-}" == "-dumpmachine" ]]; then echo "x86_64-w64-mingw32"; exit 0; fi',
    'if [[ "${1:-}" == "-dumpfullversion" || "${1:-}" == "-dumpversion" ]]; then echo "13.1.0"; exit 0; fi',
    'out=""',
    'previous=""',
    'for argument in "$@"; do',
    '  if [[ "$previous" == "-o" ]]; then',
    '    out="$argument"',
    '    break',
    '  fi',
    '  previous="$argument"',
    'done',
    'if [[ -z "$out" && "${1:-}" == "rcs" ]]; then',
    '  out="${2:-}"',
    'fi',
    'if [[ -z "$out" ]]; then',
    '  echo "Fake tool could not determine output path" >&2',
    '  exit 9',
    'fi',
    'mkdir -p "$(dirname "$out")"',
    'printf \'generated by %s\\n\' "$(basename "$0")" > "$out"',
    ''
  ].join('\n');
  write(filePath, script);
  fs.chmodSync(filePath, 0o755);
}

function execute(executable, args, cwd) {
  const result = spawnSync(executable, args, { cwd, encoding: 'utf8' });
  assert.strictEqual(result.status, 0, `${path.basename(executable)} failed: ${result.stderr || result.stdout}`);
}

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'qpm-qt-execution-'));
try {
  const qtBase = path.join(root, 'Qt');
  const qtRoot = path.join(qtBase, '6.8.3', 'mingw_64');
  for (const tool of ['moc', 'uic', 'rcc', 'qmake', 'windeployqt', 'designer']) makeFakeTool(path.join(qtRoot, 'bin', tool));
  for (const module of ['Core', 'Gui', 'Widgets']) fs.mkdirSync(path.join(qtRoot, 'include', `Qt${module}`), { recursive: true });
  for (const library of ['Core', 'Gui', 'Widgets']) write(path.join(qtRoot, 'lib', `libQt6${library}.a`));
  fs.mkdirSync(path.join(qtRoot, 'mkspecs', 'win32-g++'), { recursive: true });

  const toolBin = path.join(qtBase, 'Tools', 'mingw1310_64', 'bin');
  for (const tool of ['g++', 'gcc', 'ar', 'gdb', 'mingw32-make']) makeFakeTool(path.join(toolBin, tool));

  const installation = qtInstallations.describeQtRoot(qtRoot);
  assert(installation, 'Simulated Qt kit should be detected');
  assert(installation.toolchain.cppCompilerPath, 'Simulated C++ compiler should be detected');

  const projectRoot = path.join(root, 'Project');
  const manifestPath = path.join(projectRoot, 'Execution.qtproject.json');
  write(path.join(projectRoot, 'src', 'main.cpp'), '#include "mainwindow.h"\nint main(){ return 0; }\n');
  write(path.join(projectRoot, 'src', 'mainwindow.cpp'), '#include "mainwindow.h"\n#include "ui_mainwindow.h"\n');
  write(path.join(projectRoot, 'include', 'mainwindow.h'), '#pragma once\nclass MainWindow { Q_OBJECT };\n');
  write(path.join(projectRoot, 'forms', 'mainwindow.ui'), '<ui version="4.0"><class>MainWindow</class></ui>\n');
  write(path.join(projectRoot, 'resources', 'assets', 'icon.txt'), 'asset');
  write(path.join(projectRoot, 'resources', 'resources.qrc'), '<RCC><qresource><file>assets/icon.txt</file></qresource></RCC>\n');

  const manifest = model.createDefaultQtProjectManifest('Execution', 'widgets-application', ['Widgets']);
  manifest.qt.installation = qtRoot;
  manifest.files.sources = ['src/main.cpp', 'src/mainwindow.cpp'];
  manifest.files.headers = ['include/mainwindow.h'];
  manifest.files.forms = ['forms/mainwindow.ui'];
  manifest.files.resources = ['resources/resources.qrc'];
  model.writeQtProjectManifest(manifestPath, manifest);

  const plan = direct.createQtDirectBuildPlan(manifestPath, 'debug64', installation);
  fs.mkdirSync(plan.generatedDirectory, { recursive: true });
  fs.mkdirSync(plan.objectDirectory, { recursive: true });
  fs.mkdirSync(path.dirname(plan.targetPath), { recursive: true });

  for (const step of plan.generationSteps) {
    assert.strictEqual(direct.generationStepIsOutdated(step), true, `${step.kind} should initially be outdated`);
    execute(step.toolPath, step.arguments, plan.projectDirectory);
    assert(fs.existsSync(step.outputPath), `${step.kind} should create ${step.outputPath}`);
    assert.strictEqual(direct.generationStepIsOutdated(step), false, `${step.kind} should be current after generation`);
  }

  const objectFiles = [];
  for (const sourcePath of [...plan.sourceFiles, ...plan.generatedSourceFiles]) {
    const objectPath = direct.qtObjectPathForSource(plan, sourcePath);
    execute(installation.toolchain.cppCompilerPath, direct.qtCompileArguments(plan, sourcePath, objectPath), plan.projectDirectory);
    assert(fs.existsSync(objectPath), `Compiler should create ${objectPath}`);
    objectFiles.push(objectPath);
  }

  execute(installation.toolchain.cppCompilerPath, direct.qtLinkArguments(plan, objectFiles), plan.projectDirectory);
  assert(fs.existsSync(plan.targetPath), 'Linker should create the Qt target');

  const rccStep = plan.generationSteps.find(step => step.kind === 'rcc');
  assert(rccStep, 'RCC generation step should exist');
  const future = new Date(Date.now() + 2000);
  fs.utimesSync(path.join(projectRoot, 'resources', 'assets', 'icon.txt'), future, future);
  assert.strictEqual(direct.generationStepIsOutdated(rccStep), true, 'Changing a QRC payload should invalidate RCC output');

  console.log('QPM 0.2.0 direct Qt execution simulation: PASS');
} finally {
  fs.rmSync(root, { recursive: true, force: true });
  Module._load = originalLoad;
}
