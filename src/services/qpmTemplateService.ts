  async insertSnippet(requestedCategory?: SnippetCategoryId): Promise<void> {
    const editor = vscode.window.activeTextEditor;
    if (!editor) {
      vscode.window.showErrorMessage('Open a source file before inserting a Qt/C++ snippet.');
      return;
    }

    const builtIns = getBuiltInSnippets();
    const userSnippets = this.loadSnippets();
    let category = requestedCategory;
    if (!category) {
      const availableCategories = SNIPPET_CATEGORIES.filter((entry) => entry.id !== 'user' || userSnippets.length > 0);
      const selectedCategory = await vscode.window.showQuickPick(
        availableCategories.map((entry) => ({
          label: entry.label,
          description: entry.description,
          value: entry.id
        })),
        {
          title: 'QPM: Insert snippet',
          placeHolder: 'Select a snippet category',
          matchOnDescription: true
        }
      );
      if (!selectedCategory) {
        return;
      }
      category = selectedCategory.value;
    }

    if (category === 'user' && userSnippets.length === 0) {
      vscode.window.showInformationMessage('No saved QPM snippets are available yet. Select code and use “Save selection as snippet”.');
      return;
    }

    const categoryMetadata = SNIPPET_CATEGORIES.find((entry) => entry.id === category);
    const builtInItems = category === 'user'
      ? []
      : builtIns
          .filter((snippet) => category === 'all' || snippet.categories.includes(category as BuiltInSnippetCategory))
          .map((snippet) => ({
            label: snippet.label,
            description: snippet.description,
            detail: `Built-in · ${snippet.categories.map((id) => SNIPPET_CATEGORIES.find((entry) => entry.id === id)?.label ?? id).join(' / ')}`,
            body: snippet.body
          }));
    const userItems = category === 'all' || category === 'user'
      ? userSnippets.map((snippet) => ({
          label: snippet.label,
          description: snippet.description || '',
          detail: 'Saved user snippet',
          body: snippet.body
        }))
      : [];
    const items: Array<vscode.QuickPickItem & { body: string }> = [...builtInItems, ...userItems];
    if (items.length === 0) {
      vscode.window.showInformationMessage(`No snippet is available in ${categoryMetadata?.label ?? category}.`);
      return;
    }

    const selected = await vscode.window.showQuickPick(items, {
      title: `QPM snippets · ${categoryMetadata?.label ?? 'All'}`,
      placeHolder: 'Select a reusable code fragment to insert at the current cursor position',
      matchOnDescription: true,
      matchOnDetail: true
    });
    if (!selected) {
      return;
    }
    await editor.insertSnippet(new vscode.SnippetString(selected.body));
  }

