export function renderTemplateText(template: string, variables: TemplateVariables): string {
  return String(template || '').replace(/\{\{([A-Za-z0-9_]+)\}\}/g, (_match, key: string) => {
    const value = variables[key as keyof TemplateVariables];
    return value === undefined ? `{{${key}}}` : String(value);
  });
}

export function resolveUirTemplateVersion(preference: string, installationRoot?: string): 'qpm2012' | 'qpm2020' {
  const normalizedPreference = String(preference || 'auto').toLowerCase();
  if (normalizedPreference === 'qpm2020') {
    return 'qpm2020';
  }
  if (normalizedPreference === 'qpm2012') {
    return 'qpm2012';
  }
  const root = String(installationRoot || '');
  const year = root.match(/(?:QPM|LabWindows[^0-9]*)(20\d{2})/i)?.[1];
  return year && Number(year) >= 2020 ? 'qpm2020' : 'qpm2012';
}

